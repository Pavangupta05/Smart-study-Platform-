/**
 * Export an AI Artifact to PDF (markdown, flashcards, quiz, code, etc.)
 * @param {object} artifact - The artifact object { type, content, meta }
 * @param {string} title    - Optional title
 */
export async function exportArtifactToPDF(artifact, title = "StarNote AI Export") {
  const { type, content } = artifact;
  const doc = new jsPDF({ unit: "mm", format: "a4" });

  // We'll do a two-pass: estimate pages, then render
  // Pass 1: figure out total pages (simplified: add 1 page, then count)
  const pageNum = [1];
  const totalPages = [1]; // placeholder, will update after render

  let y = drawPageHeader(doc, title, `${TYPE_LABELS[type] || "Document"} · ${new Date().toLocaleDateString()}`);
  drawPageFooter(doc, 1, "—");

  if (type === "flashcards") {
    // Parse flashcards using same logic as artifactDetector.parseFlashcards
    let cards = [];

    // Bold **Q: / **A: format
    const boldFormat = [...content.matchAll(/\*\*Q\d*[:.]\*?\*?\s*(.+?)\n+\*\*A\d*[:.]\*?\*?\s*([\s\S]+?)(?=\*\*Q|\n\n\n|$)/gi)];
    if (boldFormat.length > 0) {
      cards = boldFormat.map(m => ({ question: m[1].trim(), answer: m[2].trim() }));
    } else {
      // Numbered Q: / A: format
      const lines = content.split("\n").filter(Boolean);
      let current = null;
      for (const line of lines) {
        const qMatch = line.match(/^Q\d*[:.]\s*(.+)/i);
        const aMatch = line.match(/^A\d*[:.]\s*(.+)/i);
        if (qMatch) { current = { question: qMatch[1].trim(), answer: "" }; }
        else if (aMatch && current) {
          current.answer = aMatch[1].trim();
          cards.push(current);
          current = null;
        }
      }
    }

    if (cards.length > 0) {
      renderFlashcardsPDF(doc, cards, pageNum, totalPages[0]);
    } else {
      // Fallback: render as markdown
      const tokens = parseMarkdown(content);
      renderTokens(doc, tokens, y, pageNum, totalPages[0]);
    }

  } else {
    const tokens = parseMarkdown(content);
    renderTokens(doc, tokens, y, pageNum, totalPages[0]);
  }

  // Update total page count in footers
  const total = doc.getNumberOfPages();
  for (let p = 1; p <= total; p++) {
    doc.setPage(p);
    drawPageFooter(doc, p, total);
  }

  const filename = title.replace(/[^a-z0-9]/gi, "_").toLowerCase().slice(0, 40) + ".pdf";
  doc.save(filename);
}

const TYPE_LABELS = {
  markdown: "Document",
  flashcards: "Flashcards",
  quiz: "Quiz",
  code: "Code",
  table: "Table",
  "study-plan": "Study Plan",
  mermaid: "Diagram",
};

/**
 * Export a Notes/Reader page to PDF using html2canvas to capture the visual canvas
 * @param {React.RefObject} contentRef - Ref to the DOM element to capture
 * @param {string} title - Title of the note
 */
export async function exportNoteToPDF(contentRef, title = "My Note") {
  const element = contentRef?.current;
  if (!element) return;

  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pageW = 210;
  const pageH = 297;
  const margin = 14;

  // Capture the DOM element as a high-res canvas
  const canvas = await html2canvas(element, {
    scale: 2,
    useCORS: true,
    backgroundColor: "#ffffff",
    logging: false,
    scrollX: 0,
    scrollY: 0,
    windowWidth: element.scrollWidth,
    windowHeight: element.scrollHeight,
  });

  const imgData  = canvas.toDataURL("image/jpeg", 0.92);
  const imgW     = pageW - margin * 2;
  const imgH     = (canvas.height * imgW) / canvas.width;

  // Draw header on first page
  doc.setFillColor(...COLORS.accent);
  doc.rect(0, 0, pageW, 12, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(7.5);
  doc.setTextColor(255, 255, 255);
  doc.text("⭐ StarNote AI", margin, 8);
  const now = new Date().toLocaleString("en-US", { dateStyle: "medium", timeStyle: "short" });
  doc.text(now, pageW - margin, 8, { align: "right" });

  // Title
  let y = 22;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.setTextColor(...COLORS.heading);
  doc.text(title, margin, y);
  y += 10;

  // Divider
  doc.setDrawColor(...COLORS.border);
  doc.setLineWidth(0.3);
  doc.line(margin, y, pageW - margin, y);
  y += 6;

  // Image: paginate if tall
  const contentH = pageH - y - 14;
  const totalPages = Math.ceil(imgH / contentH);

  for (let p = 0; p < totalPages; p++) {
    if (p > 0) {
      doc.addPage();
      y = 14;
    }

    // Clip and draw portion of image
    const sliceY = p * contentH;
    const sliceH = Math.min(contentH, imgH - sliceY);

    // Create a temporary canvas to slice the image
    const sliceCanvas = document.createElement("canvas");
    const ratio = canvas.width / imgW;
    sliceCanvas.width = canvas.width;
    sliceCanvas.height = sliceH * ratio;
    const sliceCtx = sliceCanvas.getContext("2d");
    sliceCtx.drawImage(canvas, 0, sliceY * ratio, canvas.width, sliceH * ratio, 0, 0, canvas.width, sliceH * ratio);

    const sliceData = sliceCanvas.toDataURL("image/jpeg", 0.92);
    doc.addImage(sliceData, "JPEG", margin, y, imgW, sliceH);

    // Footer
    const fY = pageH - 10;
    doc.setDrawColor(...COLORS.border);
    doc.setLineWidth(0.3);
    doc.line(margin, fY - 3, pageW - margin, fY - 3);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(...COLORS.muted);
    doc.text("Generated by StarNote AI", margin, fY);
    doc.text(`Page ${p + 1} of ${totalPages}`, pageW - margin, fY, { align: "right" });
  }

  const filename = title.replace(/[^a-z0-9]/gi, "_").toLowerCase().slice(0, 40) + ".pdf";
  doc.save(filename);
}
